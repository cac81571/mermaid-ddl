package jp.mermaidddl;

import static org.junit.jupiter.api.Assertions.*;

import java.util.ArrayList;
import java.util.List;
import javax.swing.text.Segment;
import jp.mermaidddl.ui.editor.MermaidErTokenMaker;
import jp.mermaidddl.ui.editor.OracleH2SqlTokenMaker;
import org.fife.ui.rsyntaxtextarea.Token;
import org.fife.ui.rsyntaxtextarea.TokenMaker;
import org.junit.jupiter.api.Test;

/** エディタのシンタックスハイライト（トークン分割）のテスト */
class SyntaxHighlightTest {

    record Tok(String text, int type, int offset) {}

    static List<Tok> tokens(TokenMaker tm, String line, int startOffset) {
        Segment seg = new Segment(line.toCharArray(), 0, line.length());
        List<Tok> out = new ArrayList<>();
        for (Token t = tm.getTokenList(seg, Token.NULL, startOffset); t != null && t.isPaintable(); t = t.getNextToken()) {
            out.add(new Tok(t.getLexeme(), t.getType(), t.getOffset()));
        }
        return out;
    }

    static List<Tok> tokens(TokenMaker tm, String line) { return tokens(tm, line, 0); }

    static int typeOf(List<Tok> toks, String text) {
        return toks.stream().filter(t -> t.text.equals(text)).findFirst()
                .orElseThrow(() -> new AssertionError("トークンがありません: " + text + " in " + toks)).type;
    }

    /** 全トークンをつなぐと元の行に戻る（取りこぼし・重複が無い） */
    static void assertCovers(List<Tok> toks, String line, int startOffset) {
        StringBuilder sb = new StringBuilder();
        int pos = startOffset;
        for (Tok t : toks) {
            assertEquals(pos, t.offset, "オフセット: " + t);
            sb.append(t.text);
            pos += t.text.length();
        }
        assertEquals(line, sb.toString());
    }

    // ------------------------------------------------------------ Mermaid

    @Test
    void mermaidKeywordAndEntity() {
        List<Tok> t = tokens(new MermaidErTokenMaker(), "erDiagram");
        assertEquals(Token.RESERVED_WORD, typeOf(t, "erDiagram"));
        t = tokens(new MermaidErTokenMaker(), "    CUSTOMER[\"顧客 (CUSTOMER)\"] {");
        assertEquals(Token.IDENTIFIER, typeOf(t, "CUSTOMER"));
        assertEquals(Token.LITERAL_STRING_DOUBLE_QUOTE, typeOf(t, "\"顧客 (CUSTOMER)\""));
        assertEquals(Token.SEPARATOR, typeOf(t, "{"));
    }

    @Test
    void mermaidAttributeWithKeysAndTags() {
        String line = "        varchar2(100) NAME PK, FK \"氏名 [NOT NULL] [DEFAULT 'x']\"";
        List<Tok> t = tokens(new MermaidErTokenMaker(), line, 40);
        assertCovers(t, line, 40);
        assertEquals(Token.DATA_TYPE, typeOf(t, "varchar2(100)"));
        assertEquals(Token.IDENTIFIER, typeOf(t, "NAME"));
        assertEquals(Token.RESERVED_WORD_2, typeOf(t, "PK"));
        assertEquals(Token.RESERVED_WORD_2, typeOf(t, "FK"));
        assertEquals(Token.LITERAL_STRING_DOUBLE_QUOTE, typeOf(t, "\"氏名 "));
        assertEquals(Token.ANNOTATION, typeOf(t, "[NOT NULL]"));
        assertEquals(Token.ANNOTATION, typeOf(t, "[DEFAULT 'x']"));
        assertEquals(Token.LITERAL_STRING_DOUBLE_QUOTE, typeOf(t, "\""));
    }

    @Test
    void mermaidCardinality() {
        for (String rel : new String[]{"||--o{", "|o..o|", "}|--|{", "}o..||", "||--||"}) {
            String line = "    CUSTOMER " + rel + " ORDERS : \"注文する\"";
            List<Tok> t = tokens(new MermaidErTokenMaker(), line);
            assertCovers(t, line, 0);
            assertEquals(Token.OPERATOR, typeOf(t, rel), rel);
            assertEquals(Token.OPERATOR, typeOf(t, ":"));
            assertEquals(Token.IDENTIFIER, typeOf(t, "ORDERS"));
            assertEquals(Token.LITERAL_STRING_DOUBLE_QUOTE, typeOf(t, "\"注文する\""));
        }
    }

    @Test
    void mermaidCommentsAndOddNames() {
        List<Tok> t = tokens(new MermaidErTokenMaker(), "  %% コメント PK [NOT NULL]");
        assertEquals(Token.COMMENT_EOL, typeOf(t, "%% コメント PK [NOT NULL]"));
        String line = "    LINE-ITEM { `Mixed Case` 顧客ID string order_no \"未閉";
        t = tokens(new MermaidErTokenMaker(), line);
        assertCovers(t, line, 0);
        assertEquals(Token.IDENTIFIER, typeOf(t, "LINE-ITEM"));
        assertEquals(Token.VARIABLE, typeOf(t, "`Mixed Case`"));
        assertEquals(Token.IDENTIFIER, typeOf(t, "顧客ID"));
        assertEquals(Token.DATA_TYPE, typeOf(t, "string"));
        assertEquals(Token.IDENTIFIER, typeOf(t, "order_no"));
        assertEquals(Token.LITERAL_STRING_DOUBLE_QUOTE, typeOf(t, "\"未閉"));
    }

    @Test
    void mermaidEmptyLine() {
        assertTrue(tokens(new MermaidErTokenMaker(), "").isEmpty());
    }

    // ------------------------------------------------------------ SQL（Oracle / H2）

    @Test
    void sqlOracleTypesAndKeywords() {
        String line = "  ID NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY, NAME VARCHAR2(50 CHAR) NOT NULL, BODY CLOB";
        List<Tok> t = tokens(new OracleH2SqlTokenMaker(), line);
        assertCovers(t, line, 0);
        assertEquals(Token.DATA_TYPE, typeOf(t, "NUMBER"));
        assertEquals(Token.DATA_TYPE, typeOf(t, "VARCHAR2"));
        assertEquals(Token.DATA_TYPE, typeOf(t, "CLOB"));
        assertEquals(Token.RESERVED_WORD, typeOf(t, "GENERATED"));
        assertEquals(Token.RESERVED_WORD, typeOf(t, "IDENTITY"));
        assertEquals(Token.IDENTIFIER, typeOf(t, "ID"));
        assertEquals(Token.IDENTIFIER, typeOf(t, "BODY"));
        assertEquals(Token.LITERAL_NUMBER_DECIMAL_INT, typeOf(t, "10"));
    }

    @Test
    void sqlStorageCommentsAndStrings() {
        List<Tok> t = tokens(new OracleH2SqlTokenMaker(), ") TABLESPACE USERS PCTFREE 10 NOLOGGING; -- 注文");
        assertEquals(Token.RESERVED_WORD, typeOf(t, "TABLESPACE"));
        assertEquals(Token.RESERVED_WORD, typeOf(t, "PCTFREE"));
        assertEquals(Token.RESERVED_WORD, typeOf(t, "NOLOGGING"));
        assertEquals(Token.IDENTIFIER, typeOf(t, "USERS"));
        assertEquals(Token.COMMENT_EOL, typeOf(t, "-- 注文"));
        t = tokens(new OracleH2SqlTokenMaker(), "COMMENT ON TABLE CUSTOMER IS '顧客';");
        assertEquals(Token.RESERVED_WORD, typeOf(t, "COMMENT"));
        assertEquals(Token.LITERAL_CHAR, typeOf(t, "'顧客'"));
        t = tokens(new OracleH2SqlTokenMaker(), "CREATE TABLE \"Mixed\" (X TIMESTAMP DEFAULT SYSTIMESTAMP, Y BINARY_DOUBLE)");
        assertEquals(Token.RESERVED_WORD, typeOf(t, "CREATE"));
        assertEquals(Token.DATA_TYPE, typeOf(t, "TIMESTAMP"));
        assertEquals(Token.DATA_TYPE, typeOf(t, "BINARY_DOUBLE"));
        assertEquals(Token.RESERVED_WORD, typeOf(t, "SYSTIMESTAMP"));
    }

    @Test
    void extraDictionaryIsCaseInsensitive() {
        assertEquals(Token.DATA_TYPE, OracleH2SqlTokenMaker.extraType("varchar2"));
        assertEquals(Token.FUNCTION, OracleH2SqlTokenMaker.extraType("Nvl"));
        assertEquals(-1, OracleH2SqlTokenMaker.extraType("CUSTOMER"));
    }

    // ------------------------------------------------------------ エディタ

    @Test
    void editorErrorLinesAndUndo() throws Exception {
        org.fife.ui.rsyntaxtextarea.RSyntaxTextArea a = jp.mermaidddl.ui.editor.Editors.create(jp.mermaidddl.ui.editor.Editors.SYNTAX_SQL);
        org.fife.ui.rtextarea.RTextScrollPane sp = jp.mermaidddl.ui.editor.Editors.scroll(a);
        a.setText("CREATE TABLE A (\n  X NUMBER\n);\n");
        sp.setSize(400, 300);
        sp.doLayout();
        a.setSize(380, 300);
        jp.mermaidddl.ui.editor.Editors.markErrorLines(a, java.util.Set.of(2, 99));
        assertEquals(1, sp.getGutter().getTrackingIcons(new java.awt.Point(0, a.yForLine(1) + 2)).length);
        jp.mermaidddl.ui.editor.Editors.clearErrors(a);
        assertEquals(0, sp.getGutter().getTrackingIcons(new java.awt.Point(0, a.yForLine(1) + 2)).length);
        // 日本語を表示できるフォント
        assertEquals(-1, a.getFont().canDisplayUpTo("顧客ID"));
        // 元に戻す
        a.discardAllEdits();
        a.append("-- 追加");
        assertTrue(a.canUndo());
        a.undoLastAction();
        assertFalse(a.getText().contains("追加"));
    }
}
