package jp.mermaidddl;

import static org.junit.jupiter.api.Assertions.*;

import java.util.List;
import jp.mermaidddl.schema.ColumnDef;
import jp.mermaidddl.schema.DdlParser;
import jp.mermaidddl.schema.Dialect;
import jp.mermaidddl.schema.Generation;
import jp.mermaidddl.schema.LogicalType;
import jp.mermaidddl.schema.SchemaModel;
import jp.mermaidddl.schema.TableDef;
import org.junit.jupiter.api.Test;

/** H2 DDL の解析テスト */
class DdlParserH2Test {

    static final String H2_DDL = """
            CREATE SEQUENCE IF NOT EXISTS PUBLIC.PRODUCT_CODE_SEQ START WITH 1000;
            CREATE TABLE IF NOT EXISTS PUBLIC.PRODUCT (
                ID          BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
                CODE        INTEGER DEFAULT NEXT VALUE FOR PUBLIC.PRODUCT_CODE_SEQ NOT NULL,
                NAME        CHARACTER VARYING(100) NOT NULL COMMENT '商品名',
                NAME_KANA   VARCHAR_IGNORECASE(100),
                PRICE       NUMERIC(10, 2) DEFAULT 0,
                RATE        DOUBLE PRECISION,
                STOCK       INT,
                ACTIVE      BOOLEAN DEFAULT TRUE,
                RELEASED_ON DATE,
                UPDATED_AT  TIMESTAMP WITH TIME ZONE,
                OPEN_AT     TIME(0),
                NOTE        CHARACTER LARGE OBJECT,
                IMAGE       BINARY VARYING(1024),
                TAGS        VARCHAR(20) ARRAY,
                UID         UUID,
                TOTAL       NUMERIC(12,2) GENERATED ALWAYS AS (PRICE * STOCK),
                CONSTRAINT PRODUCT_CODE_UK UNIQUE (CODE)
            );
            COMMENT ON TABLE PUBLIC.PRODUCT IS '商品';
            COMMENT ON COLUMN PUBLIC.PRODUCT.PRICE IS '単価';
            CREATE INDEX IDX_PRODUCT_NAME ON PUBLIC.PRODUCT(NAME);
            CREATE TABLE LEGACY (ID IDENTITY, SEQ_NO INT AUTO_INCREMENT, NAME VARCHAR(10));
            CREATE MEMORY TABLE "Quoted" ("id" INT PRIMARY KEY, "Name" VARCHAR(10));
            """;

    @Test
    void H2のDDLを解析する() {
        SchemaModel m = new DdlParser(Dialect.H2).parse(H2_DDL);
        assertTrue(m.getWarnings().isEmpty(), m.getWarnings().toString());
        assertEquals(3, m.getTables().size());
        assertTrue(m.getSequences().contains("PRODUCT_CODE_SEQ"));
        assertTrue(m.getSkipped().contains("CREATE INDEX"));

        TableDef p = m.table("PUBLIC", "PRODUCT");
        assertEquals("商品", p.getComment());
        assertEquals(List.of("ID"), p.getPrimaryKey());
        assertEquals(Generation.IDENTITY_BY_DEFAULT, p.column("ID").getGeneration());
        assertEquals(Generation.SEQUENCE_DEFAULT, p.column("CODE").getGeneration());
        assertEquals("PRODUCT_CODE_SEQ", p.column("CODE").getSequenceName());
        ColumnDef name = p.column("NAME");
        assertEquals("CHARACTER VARYING", name.getTypeName());
        assertEquals(100, name.getLength());
        assertTrue(name.getCharSemantics(), "H2 の長さは文字数");
        assertEquals("商品名", name.getComment(), "インライン COMMENT");
        assertFalse(name.getNullable());
        assertEquals("単価", p.column("PRICE").getComment());

        assertEquals(LogicalType.STRING, p.column("NAME_KANA").getLogicalType());
        assertEquals(LogicalType.DECIMAL, p.column("PRICE").getLogicalType());
        assertEquals(10, p.column("PRICE").getPrecision());
        assertEquals(2, p.column("PRICE").getScale());
        assertEquals(LogicalType.DECIMAL, p.column("RATE").getLogicalType());
        assertEquals(LogicalType.INTEGER, p.column("STOCK").getLogicalType());
        assertEquals(LogicalType.BOOLEAN, p.column("ACTIVE").getLogicalType());
        assertEquals("TRUE", p.column("ACTIVE").getDefaultExpr());
        assertEquals(LogicalType.DATE, p.column("RELEASED_ON").getLogicalType());
        assertEquals(LogicalType.DATETIME_TZ, p.column("UPDATED_AT").getLogicalType());
        assertEquals(LogicalType.TIME, p.column("OPEN_AT").getLogicalType());
        assertEquals(LogicalType.CLOB, p.column("NOTE").getLogicalType());
        assertEquals(LogicalType.BINARY, p.column("IMAGE").getLogicalType());
        assertEquals(LogicalType.OTHER, p.column("TAGS").getLogicalType());
        assertEquals(LogicalType.OTHER, p.column("UID").getLogicalType());
        assertEquals(Generation.VIRTUAL, p.column("TOTAL").getGeneration());

        TableDef legacy = m.table(null, "LEGACY");
        assertEquals(Generation.AUTO_INCREMENT, legacy.column("ID").getGeneration());
        assertEquals("BIGINT", legacy.column("ID").getTypeName());
        assertEquals(Generation.AUTO_INCREMENT, legacy.column("SEQ_NO").getGeneration());

        TableDef q = m.table(null, "Quoted");
        assertNotNull(q);
        assertEquals(List.of("id"), q.getPrimaryKey());
        assertNotNull(q.column("Name"));
    }
}
