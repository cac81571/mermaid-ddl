package jp.mermaidddl.schema

import groovy.transform.CompileStatic

/** 対象 DB の方言。主対象は H2 と Oracle。 */
@CompileStatic
enum Dialect {
    H2('H2'), ORACLE('Oracle')

    final String label

    Dialect(String label) { this.label = label }

    /** DatabaseMetaData#getDatabaseProductName から判定する（H2 / Oracle 以外は null）。 */
    static Dialect detect(String productName) {
        String p = (productName ?: '').toLowerCase(Locale.ROOT)
        if (p.contains('oracle')) return ORACLE
        if (p.contains('h2')) return H2
        null
    }

    @Override
    String toString() { label }
}

/** 型の大分類（型変換・IDENTITY 判定などに使う） */
@CompileStatic
enum LogicalType {
    STRING, CLOB, INTEGER, DECIMAL, DATE, DATETIME, DATETIME_TZ, TIME, BOOLEAN,
    /** BLOB / RAW など */
    BINARY,
    /** ROWID / INTERVAL / XMLTYPE / JSON など */
    OTHER

    boolean isNumeric() { this == INTEGER || this == DECIMAL }
}

/** 列値の自動生成方式 */
@CompileStatic
enum Generation {
    NONE,
    /** GENERATED ALWAYS AS IDENTITY */
    IDENTITY_ALWAYS,
    /** GENERATED BY DEFAULT AS IDENTITY */
    IDENTITY_BY_DEFAULT,
    /** GENERATED BY DEFAULT ON NULL AS IDENTITY（Oracle）／DEFAULT ON NULL */
    IDENTITY_ON_NULL,
    /** H2 の AUTO_INCREMENT / IDENTITY */
    AUTO_INCREMENT,
    /** DEFAULT seq.NEXTVAL / DEFAULT NEXT VALUE FOR seq */
    SEQUENCE_DEFAULT,
    /** BEFORE INSERT トリガーで :NEW.col := seq.NEXTVAL（Oracle 11g 以前の定番） */
    TRIGGER_SEQUENCE,
    /** 仮想列・計算列（GENERATED ALWAYS AS (式)） */
    VIRTUAL

    boolean isIdentity() { this in [IDENTITY_ALWAYS, IDENTITY_BY_DEFAULT, IDENTITY_ON_NULL, AUTO_INCREMENT] }
}

/** 列定義 */
@CompileStatic
class ColumnDef {
    String name
    /** "..." で引用された識別子（大文字小文字を保持） */
    boolean quoted
    /** 正規化した型名（例: VARCHAR2, NUMBER, TIMESTAMP WITH TIME ZONE）。仮想列で型省略時は null */
    String typeName
    /** DDL / ディクショナリ上の元の型表記 */
    String rawType
    Integer length
    /** VARCHAR2(10 CHAR) のような文字数指定（false = バイト数） */
    boolean charSemantics
    Integer precision
    Integer scale
    boolean nullable = true
    String defaultExpr
    Generation generation = Generation.NONE
    String sequenceName
    /** 仮想列（GENERATED ALWAYS AS (式)）の式 */
    String virtualExpr
    String comment
    LogicalType logicalType = LogicalType.OTHER
    int position

    @Override
    String toString() { "${name} ${rawType ?: typeName}" }
}

/** 制約定義（P=主キー, U=一意, R=外部キー, C=チェック） */
@CompileStatic
class ConstraintDef {
    String name
    String type
    List<String> columns = []
    String refTable
    List<String> refColumns = []
    String checkExpr
}

/** テーブル定義 */
@CompileStatic
class TableDef {
    String schema
    String name
    boolean quoted
    String comment
    /** TABLE / VIEW */
    String tableType = 'TABLE'
    List<ColumnDef> columns = []
    List<ConstraintDef> constraints = []
    /** 主キー採番に使えそうなシーケンス（命名規則から推定） */
    List<String> candidateSequences = []
    /** 解析時の注意事項（無視したストレージ句など） */
    List<String> notes = []

    ColumnDef column(String n) {
        columns.find { it.name == n } ?: columns.find { it.name.equalsIgnoreCase(n) }
    }

    ConstraintDef getPrimaryKeyConstraint() { constraints.find { it.type == 'P' } }

    List<String> getPrimaryKey() { primaryKeyConstraint?.columns ?: [] }

    String getQualifiedName() { schema ? "${schema}.${name}" : name }

    @Override
    String toString() { qualifiedName }
}

/** DDL 解析・メタデータ取得の結果 */
@CompileStatic
class SchemaModel {
    List<TableDef> tables = []
    /** 定義されたシーケンス名（スキーマなし・正規化済み） */
    Set<String> sequences = new LinkedHashSet<>()
    List<String> warnings = []
    /** 解析対象外としてスキップした文の種類（CREATE INDEX など） */
    List<String> skipped = []

    TableDef table(String schema, String name) {
        List<TableDef> byName = tables.findAll { it.name == name }
        if (schema) {
            TableDef exact = byName.find { it.schema == schema }
            if (exact) return exact
        }
        byName.size() >= 1 ? byName[0] : tables.find { it.name.equalsIgnoreCase(name) }
    }
}
