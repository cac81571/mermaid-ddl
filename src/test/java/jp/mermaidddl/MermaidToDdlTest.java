    @Test
    void 生成したDDLをH2で実行() throws Exception {
        runOn("jdbc:h2:mem:er_h2;DB_CLOSE_DELAY=-1", Dialect.H2);
    }

    @Test
    void 生成したDDLをH2のOracleモードで実行() throws Exception {
        runOn("jdbc:h2:mem:er_ora;MODE=Oracle;DB_CLOSE_DELAY=-1", Dialect.ORACLE);
    }

    static final String FULL = String.join("\n", "erDiagram",
            MainFrame.SAMPLE.substring("erDiagram\n".length()),
            "    EMPLOYEE[\"社員\"] {",
            "        int emp_id PK \"社員ID [IDENTITY]\"",
            "        int manager_id FK \"上司\"",
            "        string(50) name \"氏名 [NOT NULL]\"",
            "        bool active \"在籍 [DEFAULT 1]\"",
            "        text memo",
            "        blob photo",
            "        timestamptz updated_at",
            "    }",
            "    EMPLOYEE |o--o{ EMPLOYEE : \"上司\"",
            "    ACCOUNT { int account_id PK\n int emp_id FK }",
            "    EMPLOYEE ||--o| ACCOUNT : \"アカウント\"");

    private static void runOn(String url, Dialect d) throws Exception {
        DdlOptions o = opts(d);
        o.setIncludeDrop(true);
        String ddl = convert(FULL.replace("[DEFAULT 1]", d == Dialect.H2 ? "[DEFAULT TRUE]" : "[DEFAULT 1]"), o).getText();
        try (Connection c = DriverManager.getConnection(url, "sa", "")) {
            ErDdlService.ExecReport rep = ErDdlService.executeDdl(c, ddl);
            assertTrue(rep.isOk(), () -> rep.summary() + "\n" + rep.getFailedStatement() + "\n" + ddl);
            // 2 回目（DROP してから作り直す）
            ErDdlService.ExecReport rep2 = ErDdlService.executeDdl(c, ddl);
            assertTrue(rep2.isOk(), rep2::summary);
            assertTrue(rep2.getSkipped().isEmpty());

            try (Statement st = c.createStatement()) {
                st.execute("INSERT INTO CUSTOMER (CUSTOMER_ID, NAME, EMAIL) VALUES (1, '山田', 'y@example.com')");
                st.execute("INSERT INTO PRODUCT (PRODUCT_CODE, PRODUCT_NAME, PRICE) VALUES ('P1', '鉛筆', 100.50)");
                st.execute("INSERT INTO ORDERS (CUSTOMER_ID, AMOUNT) VALUES (1, 201.00)"); // IDENTITY + DEFAULT
                ResultSet rs = st.executeQuery("SELECT ORDER_ID, ORDERED_AT FROM ORDERS");
                assertTrue(rs.next());
                assertEquals(1, rs.getInt(1), "IDENTITY で採番");
                assertNotNull(rs.getTimestamp(2), "DEFAULT CURRENT_TIMESTAMP");
                st.execute("INSERT INTO ORDER_ITEM (ORDER_ID, LINE_NO, PRODUCT_CODE, QUANTITY) VALUES (1, 1, 'P1', 2)");
                // FK 違反
                assertThrows(SQLException.class, () -> st.execute("INSERT INTO ORDERS (CUSTOMER_ID, AMOUNT) VALUES (99, 1)"));
                // FK 列は NOT NULL（||）
                assertThrows(SQLException.class, () -> st.execute("INSERT INTO ORDER_ITEM (ORDER_ID, LINE_NO, QUANTITY) VALUES (1, 2, 1)"));
                // 一意制約
                assertThrows(SQLException.class, () -> st.execute("INSERT INTO CUSTOMER (CUSTOMER_ID, NAME, EMAIL) VALUES (2, '佐藤', 'y@example.com')"));
                // 自己参照（NULL 可）と 1 対 1（UNIQUE）
                st.execute("INSERT INTO EMPLOYEE (NAME) VALUES ('部長')");
                st.execute("INSERT INTO EMPLOYEE (NAME, MANAGER_ID) VALUES ('課長', 1)");
                st.execute("INSERT INTO ACCOUNT (ACCOUNT_ID, EMP_ID) VALUES (1, 1)");
                assertThrows(SQLException.class, () -> st.execute("INSERT INTO ACCOUNT (ACCOUNT_ID, EMP_ID) VALUES (2, 1)"));
                // DROP で子から消せること（CASCADE）
            }
            // コメント（H2 の INFORMATION_SCHEMA で確認）
            try (PreparedStatement ps = c.prepareStatement(
                    "SELECT REMARKS FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'CUSTOMER' AND COLUMN_NAME = 'NAME'")) {
                ResultSet rs = ps.executeQuery();
                assertTrue(rs.next());
                assertEquals("氏名", rs.getString(1));
            }
        }
    }

    @Test
    void 実行エラーは行番号を返す() throws Exception {
        try (Connection c = DriverManager.getConnection("jdbc:h2:mem:er_err", "sa", "")) {
            ErDdlService.ExecReport rep = ErDdlService.executeDdl(c, "CREATE TABLE A (ID INT);\n\n-- コメント\nCREATE TABLE A (ID INT);\n");
            assertFalse(rep.isOk());
            assertEquals(4, rep.getFailedLine());
            assertEquals(1, rep.getExecuted());
        }
    }

    @Test
    void 列のNULL可否() {
        ErDdlService.Result r = convert(FULL, opts(Dialect.H2));
        TableDef emp = r.getModel().table(null, "EMPLOYEE");
        ColumnDef id = emp.column("EMP_ID");
        assertFalse(id.getNullable());
        assertTrue(emp.column("MEMO").getNullable());
        assertFalse(emp.column("NAME").getNullable());
        assertFalse(r.getModel().table(null, "ACCOUNT").column("EMP_ID").getNullable());
    }
