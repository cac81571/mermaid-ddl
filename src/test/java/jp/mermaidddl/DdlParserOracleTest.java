    /** SQL Developer のエクスポート形式（引用識別子・スキーマ・ストレージ句・ENABLE・USING INDEX） */
    static final String SQLDEV_DDL = """
            --------------------------------------------------------
            --  DDL for Table EMPLOYEE
            --------------------------------------------------------

              CREATE TABLE "HR"."EMPLOYEE"
               (	"EMP_ID" NUMBER(10,0) GENERATED ALWAYS AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
            	"EMP_NAME" VARCHAR2(50 CHAR) NOT NULL ENABLE,
            	"KANA" VARCHAR2(100 BYTE),
            	"EMAIL" VARCHAR2(200),
            	"SALARY" NUMBER(10,2) DEFAULT 0,
            	"BONUS_RATE" NUMBER,
            	"DEPT_ID" NUMBER(*,0),
            	"HIRE_DATE" DATE DEFAULT SYSDATE NOT NULL ENABLE,
            	"UPDATED_AT" TIMESTAMP (6) WITH LOCAL TIME ZONE,
            	"CREATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP,
            	"PROFILE" CLOB,
            	"PHOTO" BLOB,
            	"Mixed Case" CHAR(1 BYTE) DEFAULT 'N',
            	"ANNUAL" NUMBER GENERATED ALWAYS AS ("SALARY"*12) VIRTUAL ,
            	"PROBATION" INTERVAL DAY (2) TO SECOND (6),
            	 CONSTRAINT "EMPLOYEE_PK" PRIMARY KEY ("EMP_ID")
              USING INDEX PCTFREE 10 INITRANS 2 MAXTRANS 255 COMPUTE STATISTICS
              STORAGE(INITIAL 65536 NEXT 1048576 MINEXTENTS 1 MAXEXTENTS 2147483645
              PCTINCREASE 0 FREELISTS 1 FREELIST GROUPS 1
              BUFFER_POOL DEFAULT FLASH_CACHE DEFAULT CELL_FLASH_CACHE DEFAULT)
              TABLESPACE "USERS"  ENABLE,
            	 CONSTRAINT "EMPLOYEE_EMAIL_UK" UNIQUE ("EMAIL") ENABLE,
            	 CONSTRAINT "EMPLOYEE_DEPT_FK" FOREIGN KEY ("DEPT_ID")
            	  REFERENCES "HR"."DEPT" ("DEPT_ID") ON DELETE CASCADE ENABLE,
            	 CONSTRAINT "EMPLOYEE_SALARY_CK" CHECK (salary >= 0) ENABLE
               ) SEGMENT CREATION IMMEDIATE
              PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255
             NOCOMPRESS LOGGING
              STORAGE(INITIAL 65536 NEXT 1048576 MINEXTENTS 1 MAXEXTENTS 2147483645
              PCTINCREASE 0 FREELISTS 1 FREELIST GROUPS 1
              BUFFER_POOL DEFAULT FLASH_CACHE DEFAULT CELL_FLASH_CACHE DEFAULT)
              TABLESPACE "USERS"
             LOB ("PROFILE") STORE AS SECUREFILE (
              TABLESPACE "USERS" ENABLE STORAGE IN ROW CHUNK 8192
              NOCACHE LOGGING  NOCOMPRESS  KEEP_DUPLICATES ) ;

               COMMENT ON COLUMN "HR"."EMPLOYEE"."EMP_ID" IS '社員ID';
               COMMENT ON COLUMN "HR"."EMPLOYEE"."EMP_NAME" IS '氏名';
               COMMENT ON COLUMN "HR"."EMPLOYEE"."KANA" IS q'[フリガナ（'全角'）]';
               COMMENT ON COLUMN "HR"."EMPLOYEE"."HIRE_DATE" IS '入社日''s';
               COMMENT ON TABLE "HR"."EMPLOYEE"  IS '社員マスタ';
            --------------------------------------------------------
            --  DDL for Index EMPLOYEE_PK
            --------------------------------------------------------

              CREATE UNIQUE INDEX "HR"."EMPLOYEE_PK" ON "HR"."EMPLOYEE" ("EMP_ID")
              PCTFREE 10 INITRANS 2 MAXTRANS 255 COMPUTE STATISTICS
              TABLESPACE "USERS" ;
            """;

    private static TableDef parseOne(String ddl) {
        SchemaModel m = new DdlParser(Dialect.ORACLE).parse(ddl);
        assertEquals(1, m.getTables().size(), "warnings=" + m.getWarnings());
        return m.getTables().get(0);
    }

    /** ユーザーから報告された実機の DDL（SQL Developer の出力そのまま。タブ・空行・二重空白を含む） */
    static final String USER02_ORDERS = "CREATE TABLE \"USER02\".\"ORDERS\" \n"
            + "   (\t\"ORDER_ID\" NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, \n"
            + "\t\"CUSTOMER_ID\" NUMBER(10,0), \n"
            + "\n"
            + "\t\"ORDERED_AT\" TIMESTAMP (6) DEFAULT CURRENT_TIMESTAMP, \n"
            + "\t\"AMOUNT\" NUMBER(10,2), \n"
            + "\t CONSTRAINT \"PK_ORDERS\" PRIMARY KEY (\"ORDER_ID\")\n"
            + "  USING INDEX PCTFREE 10 INITRANS 2 MAXTRANS 255 \n"
            + "  TABLESPACE \"TS_USER02\"  ENABLE\n"
            + "   ) SEGMENT CREATION DEFERRED \n"
            + "  PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255 \n"
            + " NOCOMPRESS LOGGING\n"
            + "  TABLESPACE \"TS_USER02\" ";

    @Test
    void 報告された実機DDL_IDENTITYオプション_DEFAULT_CURRENT_TIMESTAMP_USING_INDEX_ストレージ句() {
        SchemaModel m = new DdlParser(Dialect.ORACLE).parse(USER02_ORDERS);
        assertTrue(m.getWarnings().isEmpty(), m.getWarnings().toString());
        assertEquals(1, m.getTables().size());
        TableDef t = m.getTables().get(0);
        assertEquals("USER02", t.getSchema());
        assertEquals("ORDERS", t.getName());
        assertEquals(List.of("ORDER_ID", "CUSTOMER_ID", "ORDERED_AT", "AMOUNT"),
                t.getColumns().stream().map(ColumnDef::getName).collect(java.util.stream.Collectors.toList()));
        ColumnDef id = t.column("ORDER_ID");
        assertEquals(Generation.IDENTITY_BY_DEFAULT, id.getGeneration());
        assertFalse(id.getNullable());
        assertEquals(10, id.getPrecision());
        assertEquals(0, id.getScale());
        assertEquals(LogicalType.INTEGER, id.getLogicalType());
        assertNull(id.getDefaultExpr());
        ColumnDef cust = t.column("CUSTOMER_ID");
        assertTrue(cust.getNullable());
        assertEquals(Generation.NONE, cust.getGeneration());
        ColumnDef at = t.column("ORDERED_AT");
        assertEquals("TIMESTAMP", at.getTypeName());
        assertEquals(6, at.getScale() != null ? at.getScale() : at.getPrecision());
        assertEquals("CURRENT_TIMESTAMP", at.getDefaultExpr());
        assertEquals(Generation.NONE, at.getGeneration());
        assertEquals(10, t.column("AMOUNT").getPrecision());
        assertEquals(2, t.column("AMOUNT").getScale());
        assertEquals(List.of("ORDER_ID"), t.getPrimaryKey());
        assertEquals("PK_ORDERS", t.getPrimaryKeyConstraint().getName());
        assertEquals(1, t.getConstraints().size(), "USING INDEX / TABLESPACE などは制約として扱わない");
    }

    @Test
    void SQLDeveloper形式_スキーマ_引用識別子_コメント() {
        SchemaModel m = new DdlParser(Dialect.ORACLE).parse(SQLDEV_DDL);
        assertEquals(1, m.getTables().size(), "warnings=" + m.getWarnings());
        assertTrue(m.getWarnings().isEmpty(), m.getWarnings().toString());
        assertTrue(m.getSkipped().contains("CREATE INDEX"), m.getSkipped().toString());
        TableDef t = m.getTables().get(0);
        assertEquals("HR", t.getSchema());
        assertEquals("EMPLOYEE", t.getName());
        assertEquals("社員マスタ", t.getComment());
        assertEquals(15, t.getColumns().size());
        assertEquals("社員ID", t.column("EMP_ID").getComment());
        assertEquals("フリガナ（'全角'）", t.column("KANA").getComment(), "q 引用");
        assertEquals("入社日's", t.column("HIRE_DATE").getComment(), "'' エスケープ");
        assertTrue(t.getNotes().stream().anyMatch(n -> n.contains("TABLESPACE") && n.contains("PCTFREE")), t.getNotes().toString());
    }

    @Test
    void 列の型_長さ_セマンティクス() {
        TableDef t = parseOne(SQLDEV_DDL);
        ColumnDef id = t.column("EMP_ID");
        assertEquals("NUMBER", id.getTypeName());
        assertEquals(10, id.getPrecision());
        assertEquals(0, id.getScale());
        assertEquals(LogicalType.INTEGER, id.getLogicalType());
        assertEquals(Generation.IDENTITY_ALWAYS, id.getGeneration());
        assertFalse(id.getNullable());

        ColumnDef name = t.column("EMP_NAME");
        assertEquals(50, name.getLength());
        assertTrue(name.getCharSemantics(), "50 CHAR");
        assertFalse(name.getNullable());
        ColumnDef kana = t.column("KANA");
        assertEquals(100, kana.getLength());
        assertFalse(kana.getCharSemantics(), "100 BYTE");
        assertFalse(t.column("EMAIL").getCharSemantics(), "指定なしは BYTE");

        assertEquals(LogicalType.DECIMAL, t.column("SALARY").getLogicalType());
        assertEquals("0", t.column("SALARY").getDefaultExpr());
        assertEquals(LogicalType.DECIMAL, t.column("BONUS_RATE").getLogicalType(), "精度なし NUMBER");
        ColumnDef dept = t.column("DEPT_ID");
        assertNull(dept.getPrecision(), "NUMBER(*,0)");
        assertEquals(0, dept.getScale());
        assertEquals(LogicalType.INTEGER, dept.getLogicalType());

        ColumnDef hire = t.column("HIRE_DATE");
        assertEquals(LogicalType.DATE, hire.getLogicalType());
        assertEquals("SYSDATE", hire.getDefaultExpr());
        assertFalse(hire.getNullable());
        assertEquals("TIMESTAMP WITH LOCAL TIME ZONE", t.column("UPDATED_AT").getTypeName());
        assertEquals(LogicalType.DATETIME_TZ, t.column("UPDATED_AT").getLogicalType());
        assertEquals(LogicalType.DATETIME, t.column("CREATED_AT").getLogicalType());
        assertEquals(LogicalType.CLOB, t.column("PROFILE").getLogicalType());
        assertEquals(LogicalType.BINARY, t.column("PHOTO").getLogicalType());

        ColumnDef mixed = t.column("Mixed Case");
        assertNotNull(mixed, "引用識別子は大文字小文字と空白を保持");
        assertTrue(mixed.getQuoted());
        assertEquals("'N'", mixed.getDefaultExpr());
        assertEquals(Generation.VIRTUAL, t.column("ANNUAL").getGeneration());
        assertEquals("INTERVAL DAY TO SECOND", t.column("PROBATION").getTypeName());
        assertEquals(LogicalType.OTHER, t.column("PROBATION").getLogicalType());
    }

    @Test
    void 名前付き制約() {
        TableDef t = parseOne(SQLDEV_DDL);
        assertEquals(List.of("EMP_ID"), t.getPrimaryKey());
        assertEquals("EMPLOYEE_PK", t.getPrimaryKeyConstraint().getName());
        ConstraintDef uk = t.getConstraints().stream().filter(c -> c.getType().equals("U")).findFirst().orElseThrow();
        assertEquals("EMPLOYEE_EMAIL_UK", uk.getName());
        assertEquals(List.of("EMAIL"), uk.getColumns());
        ConstraintDef fk = t.getConstraints().stream().filter(c -> c.getType().equals("R")).findFirst().orElseThrow();
        assertEquals("EMPLOYEE_DEPT_FK", fk.getName());
        assertEquals("DEPT", fk.getRefTable());
        assertEquals(List.of("DEPT_ID"), fk.getRefColumns());
        ConstraintDef ck = t.getConstraints().stream().filter(c -> c.getType().equals("C")).findFirst().orElseThrow();
        assertEquals("EMPLOYEE_SALARY_CK", ck.getName());
        assertEquals("salary >= 0", ck.getCheckExpr());
    }

    @Test
    void 引用なし識別子は大文字化_インライン制約_ALTERでの主キー() {
        String ddl = """
                create table sales.order_header (
                  order_no   number(12) constraint order_header_nn1 not null,
                  customer   varchar2(40 char) constraint order_header_cust_fk references sales.customer(cust_id),
                  status     char(1) default 'A' constraint order_status_ck check (status in ('A','C')),
                  note       nvarchar2(200),
                  amount     number(12,2) default 0 not null
                ) tablespace users pctfree 5;
                alter table sales.order_header add constraint order_header_pk primary key (order_no) using index tablespace idx;
                alter table sales.order_header modify (note not null);
                comment on table sales.order_header is '受注ヘッダ';
                comment on column order_header.amount is '金額';
                """;
        TableDef t = parseOne(ddl);
        assertEquals("SALES", t.getSchema());
        assertEquals("ORDER_HEADER", t.getName());
        assertFalse(t.getQuoted());
        assertEquals(List.of("ORDER_NO"), t.getPrimaryKey());
        assertEquals("ORDER_HEADER_PK", t.getPrimaryKeyConstraint().getName());
        assertFalse(t.column("NOTE").getNullable(), "ALTER TABLE MODIFY (col NOT NULL)");
        assertTrue(t.column("NOTE").getCharSemantics(), "NVARCHAR2 は文字数");
        ConstraintDef fk = t.getConstraints().stream().filter(c -> "R".equals(c.getType())).findFirst().orElseThrow();
        assertEquals("ORDER_HEADER_CUST_FK", fk.getName());
        assertEquals("CUSTOMER", fk.getRefTable());
        ConstraintDef ck = t.getConstraints().stream().filter(c -> "C".equals(c.getType())).findFirst().orElseThrow();
        assertEquals("ORDER_STATUS_CK", ck.getName());
        assertEquals("'A'", t.column("STATUS").getDefaultExpr());
        assertEquals("受注ヘッダ", t.getComment());
        assertEquals("金額", t.column("AMOUNT").getComment(), "スキーマなしの COMMENT も対応付ける");
    }

    @Test
    void IDENTITYの種類とDEFAULTシーケンス() {
        String ddl = """
                CREATE SEQUENCE item_code_seq;
                CREATE TABLE item (
                  id1 NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
                  id2 NUMBER GENERATED BY DEFAULT AS IDENTITY,
                  id3 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                  code NUMBER(10) DEFAULT item_code_seq.NEXTVAL,
                  code2 NUMBER(10) DEFAULT "HR"."ITEM_CODE_SEQ".nextval NOT NULL,
                  total NUMBER AS (id1 * 2),
                  CONSTRAINT item_pk PRIMARY KEY (id1)
                );
                """;
        TableDef t = parseOne(ddl);
        assertEquals(Generation.IDENTITY_ALWAYS, t.column("ID1").getGeneration());
        assertEquals(Generation.IDENTITY_BY_DEFAULT, t.column("ID2").getGeneration());
        assertEquals(Generation.IDENTITY_ON_NULL, t.column("ID3").getGeneration());
        assertEquals(Generation.SEQUENCE_DEFAULT, t.column("CODE").getGeneration());
        assertEquals("ITEM_CODE_SEQ", t.column("CODE").getSequenceName());
        assertEquals(Generation.SEQUENCE_DEFAULT, t.column("CODE2").getGeneration());
        assertFalse(t.column("CODE2").getNullable());
        assertEquals(Generation.VIRTUAL, t.column("TOTAL").getGeneration(), "短縮形の仮想列（型あり AS (式)）");
    }

    @Test
    void トリガー採番とスラッシュ区切りと命名規則によるシーケンス推定() {
        String ddl = """
                CREATE TABLE dept (
                  dept_id   NUMBER(6) PRIMARY KEY,
                  dept_name VARCHAR2(60) NOT NULL
                )
                /
                CREATE SEQUENCE dept_seq START WITH 10 INCREMENT BY 10
                /
                CREATE OR REPLACE TRIGGER dept_bi
                  BEFORE INSERT ON dept
                  FOR EACH ROW
                BEGIN
                  IF :NEW.dept_id IS NULL THEN
                    SELECT dept_seq.NEXTVAL INTO :NEW.dept_id FROM dual;
                  END IF;
                END;
                /
                CREATE TABLE emp2 (emp_id NUMBER(8) CONSTRAINT emp2_pk PRIMARY KEY, name VARCHAR2(30))
                /
                CREATE SEQUENCE emp2_seq
                /
                CREATE OR REPLACE TRIGGER "EMP2_BI" BEFORE INSERT OR UPDATE ON "EMP2" FOR EACH ROW
                BEGIN
                  :new."EMP_ID" := "EMP2_SEQ".nextval;
                END;
                /
                CREATE TABLE emp3 (emp_id NUMBER(8) CONSTRAINT emp3_pk PRIMARY KEY, name VARCHAR2(30))
                /
                CREATE SEQUENCE emp3_seq
                /
                """;
        SchemaModel m = new DdlParser(Dialect.ORACLE).parse(ddl);
        assertTrue(m.getWarnings().isEmpty(), m.getWarnings().toString());
        TableDef dept = m.table(null, "DEPT");
        assertEquals(Generation.TRIGGER_SEQUENCE, dept.column("DEPT_ID").getGeneration());
        assertEquals("DEPT_SEQ", dept.column("DEPT_ID").getSequenceName());
        assertEquals(List.of("DEPT_ID"), dept.getPrimaryKey());
        TableDef emp2 = m.table(null, "EMP2");
        assertEquals(Generation.TRIGGER_SEQUENCE, emp2.column("EMP_ID").getGeneration(), ":NEW.col := seq.NEXTVAL 形式");
        assertEquals("EMP2_SEQ", emp2.column("EMP_ID").getSequenceName());
        TableDef emp3 = m.table(null, "EMP3");
        assertEquals(Generation.NONE, emp3.column("EMP_ID").getGeneration());
        assertEquals(List.of("EMP3_SEQ"), emp3.getCandidateSequences(), "トリガーなし → 命名規則で候補に");
    }

    @Test
    void 日本語の引用識別子と一時表と未対応文() {
        String ddl = """
                CREATE GLOBAL TEMPORARY TABLE "作業表" ("番号" NUMBER(5) PRIMARY KEY, "名前" VARCHAR2(30 CHAR)) ON COMMIT DELETE ROWS;
                CREATE TABLE copy_t AS SELECT * FROM dual;
                GRANT SELECT ON "作業表" TO scott;
                CREATE OR REPLACE VIEW v AS SELECT 1 x FROM dual;
                """;
        SchemaModel m = new DdlParser(Dialect.ORACLE).parse(ddl);
        assertEquals(1, m.getTables().size());
        TableDef t = m.getTables().get(0);
        assertEquals("作業表", t.getName());
        assertTrue(t.getQuoted());
        assertEquals(List.of("番号"), t.getPrimaryKey());
        assertTrue(m.getWarnings().stream().anyMatch(w -> w.contains("COPY_T")), m.getWarnings().toString());
        assertTrue(m.getSkipped().contains("GRANT SELECT"));
        assertTrue(m.getSkipped().contains("CREATE VIEW"));
    }

    @Test
    void 識別子長の注意_30バイトと128バイト() {
        String n31 = "A".repeat(31);
        assertNull(Identifiers.checkOracleLength("列名", "A".repeat(30), 30));
        assertTrue(Identifiers.checkOracleLength("列名", n31, 30).contains("12.1 以前の上限 30 バイト"));
        assertTrue(Identifiers.checkOracleLength("列名", n31, 128).contains("12.2 以降のみ"));
        assertTrue(Identifiers.checkOracleLength("列名", "B".repeat(129), 128).contains("128 バイト"));
        // 日本語は UTF-8 で 1 文字 3 バイト: 11 文字 = 33 バイト
        assertTrue(Identifiers.checkOracleLength("列名", "あ".repeat(11), 30).contains("33 バイト"));
        assertNull(Identifiers.checkOracleLength("列名", "あ".repeat(10), 30));
    }

    @Test
    void 識別子のSQL表記とパラメータ名() {
        assertEquals("EMP_ID", Identifiers.sql("EMP_ID"));
        assertEquals("\"Mixed Case\"", Identifiers.sql("Mixed Case"));
        assertEquals("\"DATE\"", Identifiers.sql("DATE"), "予約語は引用");
        assertEquals("\"a\"\"b\"", Identifiers.sql("a\"b"));
        assertEquals("HR.EMPLOYEE", Identifiers.sql("HR", "EMPLOYEE"));
    }
