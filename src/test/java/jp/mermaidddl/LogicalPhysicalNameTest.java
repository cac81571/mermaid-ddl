package jp.mermaidddl;

import static org.junit.jupiter.api.Assertions.*;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.List;
import jp.mermaidddl.er.DdlOptions;
import jp.mermaidddl.er.ErConverter;
import jp.mermaidddl.er.ErDdlService;
import jp.mermaidddl.er.ErToSchemaOptions;
import jp.mermaidddl.er.MermaidParser;
import jp.mermaidddl.er.SchemaToErOptions;
import jp.mermaidddl.schema.Dialect;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.provider.EnumSource;
import org.junit.jupiter.api.Test;

/** エンティティの表示名「論理名 (物理名)」の出力・解析・往復変換 */
class LogicalPhysicalNameTest {

    static final String H2_DDL = String.join("\n",
            "CREATE TABLE CUSTOMER (CUSTOMER_ID INT PRIMARY KEY, NAME VARCHAR(100) NOT NULL);",
            "COMMENT ON TABLE CUSTOMER IS '顧客';",
            "COMMENT ON COLUMN CUSTOMER.NAME IS '氏名';",
            "CREATE TABLE ORDERS (ORDER_ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,",
            "  CUSTOMER_ID INT NOT NULL REFERENCES CUSTOMER (CUSTOMER_ID), ORDERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP);",
            "COMMENT ON TABLE ORDERS IS '注文';",
            "COMMENT ON COLUMN ORDERS.ORDERED_AT IS '注文日時';",
            "CREATE TABLE CODE_MASTER (CODE VARCHAR(10) PRIMARY KEY);");

    static final String ORACLE_DDL = String.join("\n",
            "CREATE TABLE \"HR\".\"CUSTOMER\" (\"CUSTOMER_ID\" NUMBER(10,0) NOT NULL ENABLE, \"NAME\" VARCHAR2(100 CHAR) NOT NULL ENABLE,",
            "  CONSTRAINT \"PK_CUSTOMER\" PRIMARY KEY (\"CUSTOMER_ID\") USING INDEX TABLESPACE \"USERS\" ENABLE) TABLESPACE \"USERS\";",
            "COMMENT ON TABLE \"HR\".\"CUSTOMER\" IS '顧客';",
            "COMMENT ON COLUMN \"HR\".\"CUSTOMER\".\"NAME\" IS '氏名';",
            "CREATE TABLE \"HR\".\"ORDERS\" (\"ORDER_ID\" NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL ENABLE,",
            "  \"CUSTOMER_ID\" NUMBER(10,0) NOT NULL ENABLE, \"ORDERED_AT\" TIMESTAMP (6) DEFAULT CURRENT_TIMESTAMP,",
            "  CONSTRAINT \"PK_ORDERS\" PRIMARY KEY (\"ORDER_ID\"),",
            "  CONSTRAINT \"FK_ORDERS_CUSTOMER\" FOREIGN KEY (\"CUSTOMER_ID\") REFERENCES \"HR\".\"CUSTOMER\" (\"CUSTOMER_ID\") ENABLE);",
            "COMMENT ON TABLE \"HR\".\"ORDERS\" IS '注文';",
            "COMMENT ON COLUMN \"HR\".\"ORDERS\".\"ORDERED_AT\" IS '注文日時';",
            "CREATE TABLE \"HR\".\"CODE_MASTER\" (\"CODE\" VARCHAR2(10) PRIMARY KEY);");

    static String ddl(Dialect d) { return d == Dialect.H2 ? H2_DDL : ORACLE_DDL; }

    static DdlOptions dop(Dialect d) {
        DdlOptions o = new DdlOptions();
        o.setDialect(d);
        return o;
    }

    static ErToSchemaOptions so(Dialect d) {
        ErToSchemaOptions o = new ErToSchemaOptions();
        o.setDialect(d);
        return o;
    }

    // ---------------------------------------------------------------- 名前の分解・組み立て

    @ParameterizedTest(name = "{0} / {1} → {2}")
    @CsvSource(delimiter = '|', nullValues = "NULL", value = {
        "顧客 (CUSTOMER)|CUSTOMER|顧客",
        "顧客(CUSTOMER)|CUSTOMER|顧客",
        "顧客（CUSTOMER）|CUSTOMER|顧客",
        "顧客 ( customer )|CUSTOMER|顧客",
        "明細 (LINE-ITEM)|LINE_ITEM|明細",
        "明細 (LINE ITEM)|LINE ITEM|明細",
        "顧客 (法人)|CUSTOMER|顧客 (法人)",
        "顧客 (CUSTOMERS)|CUSTOMER|顧客 (CUSTOMERS)",
        "顧客|CUSTOMER|顧客",
        "(CUSTOMER)|CUSTOMER|NULL",
        "取引先 (旧顧客) (CUSTOMER)|CUSTOMER|取引先 (旧顧客)",
    })
    void 表示名から論理名を取り出す(String alias, String physical, String expected) {
        assertEquals(expected, ErConverter.logicalName(alias, physical));
    }

    @Test
    void 表示名を組み立てる_二重に付けない() {
        assertEquals("顧客 (CUSTOMER)", ErConverter.displayAlias("顧客", "CUSTOMER"));
        assertEquals("顧客 (CUSTOMER)", ErConverter.displayAlias("顧客 (CUSTOMER)", "CUSTOMER"));
        assertEquals("顧客 (法人) (CUSTOMER)", ErConverter.displayAlias("顧客 (法人)", "CUSTOMER"));
        assertEquals("CUSTOMER", ErConverter.displayAlias("CUSTOMER", "CUSTOMER"), "コメントが物理名と同じなら併記しない");
        assertNull(ErConverter.displayAlias(null, "CUSTOMER"));
        assertNull(ErConverter.displayAlias("", "CUSTOMER"));
    }

    // ---------------------------------------------------------------- DDL → ER 図

    @ParameterizedTest
    @EnumSource(value = Dialect.class, names = {"H2", "ORACLE"})
    void DDLからER図_論理名と物理名を併記(Dialect d) {
        ErDdlService.Result r = ErDdlService.ddlToMermaid(ddl(d), d, new SchemaToErOptions());
        assertTrue(r.isOk(), r.getErrors().toString());
        String t = r.getText();
        assertTrue(t.contains("CUSTOMER[\"顧客 (CUSTOMER)\"] {"), t);
        assertTrue(t.contains("ORDERS[\"注文 (ORDERS)\"] {"), t);
        assertTrue(t.contains("    CODE_MASTER {"), "コメントの無い表は表示名なし: " + t);
        assertFalse(t.contains("CODE_MASTER["), t);
        // 列は従来どおり「型 物理名 キー "コメント [タグ]"」
        assertTrue(t.contains("NAME \"氏名 [NOT NULL]\""), t);
        assertTrue(t.contains("ORDERED_AT \"注文日時 [DEFAULT CURRENT_TIMESTAMP]\""), t);
        assertTrue(t.contains("ORDER_ID PK \"[IDENTITY]\""), t);
        // Mermaid として解析でき、表示名はそのまま
        assertEquals("顧客 (CUSTOMER)", new MermaidParser().parse(t).entity("CUSTOMER").getAlias());
    }

    @ParameterizedTest
    @EnumSource(value = Dialect.class, names = {"H2", "ORACLE"})
    void オプションをオフにすると論理名だけ(Dialect d) {
        SchemaToErOptions o = new SchemaToErOptions();
        o.setPhysicalNameInAlias(false);
        String t = ErDdlService.ddlToMermaid(ddl(d), d, o).getText();
        assertTrue(t.contains("CUSTOMER[\"顧客\"] {"), t);
        assertFalse(t.contains("(CUSTOMER)"), t);
    }

    // ---------------------------------------------------------------- ER 図 → DDL

    @ParameterizedTest
    @EnumSource(value = Dialect.class, names = {"H2", "ORACLE"})
    void ER図からDDL_COMMENTは論理名だけ(Dialect d) {
        String er = String.join("\n", "erDiagram",
                "    customer[\"顧客 (customer)\"] {",
                "        int customer_id PK \"顧客ID\"",
                "    }",
                "    LINE-ITEM[\"明細（LINE-ITEM）\"] {",
                "        int line_id PK",
                "        int customer_id FK",
                "    }",
                "    PARTNER[\"取引先 (法人)\"] {",
                "        int partner_id PK",
                "    }",
                "    customer ||--o{ LINE-ITEM : \"\"");
        ErDdlService.Result r = ErDdlService.mermaidToDdl(er, so(d), dop(d));
        assertTrue(r.isOk(), r.getErrors().toString());
        String sql = r.getText();
        assertTrue(sql.contains("COMMENT ON TABLE CUSTOMER IS '顧客';"), sql);
        assertTrue(sql.contains("COMMENT ON TABLE LINE_ITEM IS '明細';"), sql);
        assertTrue(sql.contains("COMMENT ON TABLE PARTNER IS '取引先 (法人)';"), "括弧内が物理名でなければそのまま: " + sql);
        assertFalse(sql.contains("(CUSTOMER)") || sql.contains("(customer)"), sql);
    }

    // ---------------------------------------------------------------- 往復

    @ParameterizedTest
    @EnumSource(value = Dialect.class, names = {"H2", "ORACLE"})
    void DDLからER図からDDL_コメントは変わらず二重にならない(Dialect d) throws Exception {
        String er1 = ErDdlService.ddlToMermaid(ddl(d), d, new SchemaToErOptions()).getText();
        ErDdlService.Result back = ErDdlService.mermaidToDdl(er1, so(d), dop(d));
        assertTrue(back.isOk(), back.getErrors().toString());
        assertTrue(back.getText().contains("COMMENT ON TABLE CUSTOMER IS '顧客';"), back.getText());
        assertTrue(back.getText().contains("COMMENT ON TABLE ORDERS IS '注文';"), back.getText());
        assertFalse(back.getText().contains("COMMENT ON TABLE CODE_MASTER"), back.getText());
        // 2 周目の ER 図は 1 周目と同じ（「顧客 (CUSTOMER) (CUSTOMER)」にならない）
        String er2 = ErDdlService.ddlToMermaid(back.getText(), d, new SchemaToErOptions()).getText();
        assertEquals(er1, er2);
        assertFalse(er2.contains("(CUSTOMER) (CUSTOMER)"));

        // 生成した DDL を実際に実行し、テーブルコメントが論理名だけになっていること
        String url = "jdbc:h2:mem:names_" + d + (d == Dialect.ORACLE ? ";MODE=Oracle" : "");
        try (Connection c = DriverManager.getConnection(url, "sa", "")) {
            assertTrue(ErDdlService.executeDdl(c, back.getText()).isOk());
            try (Statement st = c.createStatement();
                 ResultSet rs = st.executeQuery("SELECT REMARKS FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'CUSTOMER'")) {
                assertTrue(rs.next());
                assertEquals("顧客", rs.getString(1));
            }
            // DB から読込でも同じ表示名
            String fromDb = ErDdlService.dbToMermaid(c, "PUBLIC", List.of("CUSTOMER", "ORDERS", "CODE_MASTER"), new SchemaToErOptions()).getText();
            assertTrue(fromDb.contains("CUSTOMER[\"顧客 (CUSTOMER)\"]"), fromDb);
            assertTrue(fromDb.contains("    CODE_MASTER {"), fromDb);
        }
    }

    @ParameterizedTest
    @EnumSource(value = Dialect.class, names = {"H2", "ORACLE"})
    void ER図からDDLからER図_併記した表示名で一致(Dialect d) {
        String er = String.join("\n", "erDiagram",
                "    CUSTOMER[\"顧客 (CUSTOMER)\"] {",
                "        integer CUSTOMER_ID PK \"顧客ID\"",
                "        varchar(100) NAME \"氏名 [NOT NULL]\"",
                "    }",
                "    ORDERS[\"注文\"] {",
                "        integer ORDER_ID PK \"注文ID [IDENTITY]\"",
                "        integer CUSTOMER_ID FK \"顧客ID\"",
                "    }",
                "    CUSTOMER ||--o{ ORDERS : \"注文する\"");
        String sql = ErDdlService.mermaidToDdl(er, so(d), dop(d)).getText();
        String er2 = ErDdlService.ddlToMermaid(sql, d, new SchemaToErOptions()).getText();
        assertTrue(er2.contains("CUSTOMER[\"顧客 (CUSTOMER)\"]"), er2);
        assertTrue(er2.contains("ORDERS[\"注文 (ORDERS)\"]"), "論理名だけの表示名にも物理名を併記: " + er2);
        assertTrue(er2.contains("NAME \"氏名 [NOT NULL]\""), er2);
        String sql2 = ErDdlService.mermaidToDdl(er2, so(d), dop(d)).getText();
        assertEquals(sql, sql2, "DDL は往復で変わらない");
    }
}
