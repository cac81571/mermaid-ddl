    @Test
    void 名前の正規化_予約語_引用符() {
        String src = String.join("\n", "erDiagram",
                "  order { int id PK\n string user-name }",
                "  \"Line Item\"[\"明細\"] { int id PK\n int order_id FK }",
                "  顧客 { int 顧客番号 PK \"番号\" }",
                "  order ||--o{ \"Line Item\" : has");
        ErDdlService.Result r = convert(src, opts(Dialect.H2));
        String ddl = r.getText();
        assertTrue(ddl.contains("CREATE TABLE \"ORDER\" ("), ddl);
        assertTrue(ddl.contains("USER_NAME"), ddl);
        assertTrue(ddl.contains("CREATE TABLE \"Line Item\" ("), ddl);
        assertTrue(ddl.contains("REFERENCES \"ORDER\" (ID)"), ddl);
        assertTrue(ddl.contains("CREATE TABLE \"顧客\" ("), ddl);
        assertTrue(ddl.contains("COMMENT ON TABLE \"Line Item\" IS '明細';"), ddl);
        assertTrue(r.getWarnings().stream().anyMatch(w -> w.contains("予約語")), r.getWarnings().toString());

        ErToSchemaOptions keep = new ErToSchemaOptions();
        keep.setUpperCaseNames(false);
        String ddl2 = convert("erDiagram\n customer { int id PK }\n", opts(Dialect.H2), keep).getText();
        assertTrue(ddl2.contains("CREATE TABLE \"customer\" (\n    \"id\" INTEGER NOT NULL"), ddl2);
    }

    @Test
    void 整数主キーをIDENTITYにするオプション() {
        ErToSchemaOptions so = new ErToSchemaOptions();
        so.setIdentityForIntegerPk(true);
        ErDdlService.Result r = convert(MainFrame.SAMPLE, opts(Dialect.ORACLE), so);
        assertEquals(Generation.IDENTITY_BY_DEFAULT, r.getModel().table(null, "CUSTOMER").column("CUSTOMER_ID").getGeneration());
        assertEquals(Generation.NONE, r.getModel().table(null, "ORDER_ITEM").column("LINE_NO").getGeneration(), "複合主キーは対象外");
        assertEquals(Generation.NONE, r.getModel().table(null, "PRODUCT").column("PRODUCT_CODE").getGeneration(), "文字列は対象外");
    }

    @Test
    void シーケンスのDEFAULTは方言ごとに書き換える() {
        String src = "erDiagram\n T { int id PK \"[DEFAULT T_SEQ.NEXTVAL]\"\n string name }\n";
        String h2 = convert(src, opts(Dialect.H2)).getText();
        assertTrue(h2.contains("CREATE SEQUENCE T_SEQ START WITH 1 INCREMENT BY 1;"), h2);
        assertTrue(h2.contains("ID   INTEGER DEFAULT NEXT VALUE FOR T_SEQ NOT NULL"), h2);
        String ora = convert(src, opts(Dialect.ORACLE)).getText();
        assertTrue(ora.contains("ID   NUMBER(10) DEFAULT T_SEQ.NEXTVAL NOT NULL"), ora);
    }

    @Test
    void エラーがあるとDDLを出さない_属性なしエンティティ() {
        ErDdlService.Result r = ErDdlService.mermaidToDdl("erDiagram\n  A {\n    int\n  }\n", new ErToSchemaOptions(), opts(Dialect.H2));
        assertFalse(r.isOk());
        assertNull(r.getText());
        assertTrue(r.getErrors().get(0).startsWith("3 行目: "), r.getErrors().toString());

        ErDdlService.Result r2 = convert("erDiagram\n  A { int id PK }\n  B\n  A ||--o{ B : x\n", opts(Dialect.H2));
        assertFalse(r2.getText().contains("CREATE TABLE B"));
        assertTrue(r2.getWarnings().stream().anyMatch(w -> w.startsWith("3 行目") && w.contains("属性がない")), r2.getWarnings().toString());
    }

